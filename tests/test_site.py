"""
Checks on the website: the exported data agrees with the evaluation, every invoice
in the queue can be opened, the decisions follow the thresholds, and the page's
wording matches what the model actually did.
"""

import json
import re
from pathlib import Path

import pytest

from agent import route
from describe import describe_step, feature_value

DOCS = Path("docs")


@pytest.fixture(scope="module")
def site(artifacts):
    text = (DOCS / "data" / "site-data.js").read_text(encoding="utf-8")
    assert text.startswith("// Generated by src/export_site.py")
    return json.loads(text[text.index("{"): text.rstrip().rindex(";")])


def test_every_queued_invoice_has_a_case(site):
    ids = [q["id"] for q in site["queue"]]
    assert len(ids) == len(set(ids)) == site["meta"]["test_invoices"]
    assert set(ids) == set(site["cases"])


def test_queue_is_sorted_and_routed_by_the_thresholds(site):
    risks = [q["risk"] for q in site["queue"]]
    assert risks == sorted(risks, reverse=True)
    for q in site["queue"]:
        assert q["decision"] == route(q["risk"])[0] == site["cases"][q["id"]]["action"]


def test_verdicts_agree_with_ground_truth(site):
    for q in site["queue"]:
        case = site["cases"][q["id"]]
        assert case["correct"] == (bool(q["fraud"]) == (case["action"] != "RELEASE"))
        assert case["truth"].startswith("fraudulent") == bool(q["fraud"])


def test_site_numbers_match_the_evaluation(site, artifacts):
    evaluation = json.load(open("out/evaluation.json"))
    shipped = next(m for m in site["models"] if m["key"] == "tree")
    assert shipped["precision"] == pytest.approx(evaluation["performance"]["decision tree (shipped)"]["precision"], abs=1e-4)
    assert shipped["recall"] == pytest.approx(evaluation["performance"]["decision tree (shipped)"]["recall"], abs=1e-4)
    for row in site["fairness"]:
        assert row["tree"]["rate"] == pytest.approx(evaluation["fairness"][row["region"]]["shipped"], abs=1e-4)
        assert row["naive"]["rate"] == pytest.approx(evaluation["fairness"][row["region"]]["naive"], abs=1e-4)


def test_showcase_cases_are_the_three_stories(site):
    assert [s["label"] for s in site["showcase"]] == ["Impersonation caught", "Duplicate caught", "Looks guilty, isn't"]
    actions = [site["cases"][s["id"]]["action"] for s in site["showcase"]]
    assert actions[0] != "RELEASE" and actions[1] != "RELEASE" and actions[2] == "RELEASE"
    assert all(site["cases"][s["id"]]["correct"] for s in site["showcase"])


def test_page_files_exist_and_every_fact_is_defined():
    html = (DOCS / "index.html").read_text(encoding="utf-8")
    for asset in ("style.css", "charts.js", "app.js", "data/site-data.js"):
        assert f'"{asset}"' in html and (DOCS / asset).exists(), asset
    app = (DOCS / "app.js").read_text(encoding="utf-8")
    facts_block = app[app.index("const facts = {"): app.index("};", app.index("const facts = {"))]
    for fact in set(re.findall(r'data-fact="([A-Za-z]+)"', html)):
        assert re.search(rf"\b{fact}:", facts_block), f"index.html uses data-fact={fact!r} but app.js never sets it"


def test_plain_english_rules():
    yes_no = describe_step({"feature": "has_purchase_order", "value": 1.0, "threshold": 0.5, "test": "has_purchase_order > 0.50"})
    assert yes_no["value"] == "yes" and yes_no["rule"] is None

    days = describe_step({"feature": "days_since_bank_change", "value": 5.0, "threshold": 10.5, "test": "x"})
    assert days["value"] == "5 days" and days["rule"] == "at most 10 days"

    assert feature_value("days_since_bank_change", 9999.0) == "none on record"
    assert feature_value("amount_log", 9.7708) .startswith("$17,5")


def test_visitors_are_told_how_to_use_the_page(site):
    html = (DOCS / "index.html").read_text(encoding="utf-8")
    howto = html[html.index('<ol class="howto"'): html.index("</ol>", html.index('<ol class="howto"'))]
    assert howto.count("<li>") == 3
    assert 'href="#queue">Try the agent</a>' in html
    for example in site["showcase"]:
        assert len(example["blurb"]) > 40 and any(ch.isdigit() for ch in example["blurb"]), example


def test_both_dark_palettes_match():
    css = (DOCS / "style.css").read_text(encoding="utf-8")

    def tokens(selector):
        start = css.index(selector + " {")
        return re.findall(r"(--[\w-]+):\s*([^;]+);", css[start: css.index("}", start)])

    follows_device = tokens(':root:not([data-theme="light"])')
    pinned = tokens(':root[data-theme="dark"]')
    assert len(follows_device) > 10 and follows_device == pinned


def test_nav_links_every_section_in_page_order():
    html = (DOCS / "index.html").read_text(encoding="utf-8")
    nav = html[html.index('<nav class="topnav"'): html.index("</nav>")]
    targets = re.findall(r'href="#([\w-]+)"', nav)
    sections = re.findall(r'<section class="wrap section" id="([\w-]+)"', html)
    assert targets == sections
